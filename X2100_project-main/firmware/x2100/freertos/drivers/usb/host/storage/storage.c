static int storage_device_parse_inquiry(struct usb_storage_device *dev, unsigned char *inquiry_buf, u8 size)
{
	u8 dev_type;

	assert(dev);
	assert(inquiry_buf);
	assert(size >= SCSI_INQUIRY_BUFFERSIZE);

	dev_type = inquiry_buf[0] & 0x1f;

	memcpy(dev->vendor, &inquiry_buf[8], USB_STORAGE_INQUIRY_VENDOR_LEN);
	dev->vendor[USB_STORAGE_INQUIRY_VENDOR_LEN] = 0;

	memcpy(dev->product, &inquiry_buf[16], USB_STORAGE_INQUIRY_PRODUCT_LEN);
	dev->product[USB_STORAGE_INQUIRY_PRODUCT_LEN] = 0;

	memcpy(dev->version, &inquiry_buf[32], USB_STORAGE_INQUIRY_VERSION_LEN);
	dev->version[USB_STORAGE_INQUIRY_VERSION_LEN] = 0;

	printf("  Vendor: %s\n", dev->vendor);
	printf("  Product: %s\n", dev->product);
	printf("  Version: %s\n", dev->version);

	printf("  Type:   %s ",
	       dev_type < MAX_SCSI_DEVICE_CODE ? scsi_device_types[dev_type] :
	       "Unknown          ");
	printf("  ANSI SCSI revision: %02x", inquiry_buf[2] & 0x07);
	if ((inquiry_buf[2] & 0x07) == 1 && (inquiry_buf[3] & 0x0f) == 1)
		printf(" CCS\n");
	else
		printf("\n");

	printf("  Removable: %d\n", (inquiry_buf[1] & 0x80) >> 7);

	return 0;
}

static int storage_device_parse_capacity(struct usb_storage_device *dev, unsigned char *capacity_buf, u8 size)
{
	assert(dev);
	assert(capacity_buf);
	assert(size >= SCSI_CAPACITY_BUFFERSIZE);

	if (capacity_buf[0] == 0xff && capacity_buf[1] == 0xff &&
		capacity_buf[2] == 0xff && capacity_buf[3] == 0xff) {
		printf(USB_STORAGE "very big device.\n");
	}

	dev->block_count = 1 + (((u32)capacity_buf[0] << 24) | (capacity_buf[1] << 16) |
			(capacity_buf[2] << 8) | capacity_buf[3]);

	dev->block_size = (capacity_buf[4] << 24) |
		(capacity_buf[5] << 16) | (capacity_buf[6] << 8) | capacity_buf[7];

	if (dev->block_size == 0) {
		dev->block_size = 512;
		printf(USB_STORAGE "sector size 0 reported, assuming 512.\n");
	}

	if (dev->block_size != 512 && dev->block_size != 1024 &&
			dev->block_size != 2048 && dev->block_size != 4096) {
		printf(USB_STORAGE "unsupported block size %d\n", dev->block_size);
		return -EINVAL;
	}

	printf("  Block Size %d, Block Count %lld\n", dev->block_size, dev->block_count);

	return 0;
}

static void usb_stor_scan_work(void *data)
{
	int i;
	int result;
	struct usb_storage_device *dev;
	unsigned char buf[SCSI_INQUIRY_BUFFERSIZE];
	struct us_data *us = data;

	/* get max logic unit number */
	usb_stor_acquire_resources(us);

	for (i = 0; i <= us->max_lun; i++) {
		dev = &us->storage_device[i];
		dev->index = i;
		dev->user_data = NULL;
		dev->private_data = us;
		thread_waiter_init(&dev->unbind_wait);

		/* get manufacturer information */
		result = usb_stor_scsi_inquiry(us, i, buf, sizeof(buf));
		if (result)
			continue;

		/* parse inquiry buf to storage device */
		result = storage_device_parse_inquiry(dev, buf, sizeof(buf));
		if (result)
			continue;

		/* test lun ready */
		result = usb_stor_scsi_test_unit_ready(us, i);
		if (result)
			continue;

		/* read lun block_size and block_count */
		result = usb_stor_scsi_read_capacity(us, i, buf, sizeof(buf));
		if (result)
			continue;

		/* parse capacity buf to storage device */
		result = storage_device_parse_capacity(dev, buf, sizeof(buf));
		if (result)
			continue;

		/* new storage device */
		dev->bind_flag = USB_STORAGE_BIND_FLAG;
		result = usb_host_mass_storage_link_bind(dev);
		if (result) {
			dev->bind_flag = 0;
			continue;
		}
	}

	thread_waiter_wakeup(&us->exit_wait);
}

/* Probe to see if we can drive a newly-connected USB device */
static int storage_probe(struct usb_interface *intf,
			 const struct usb_device_id *id)
{
	struct us_data *us;
	const int id_index = id - storage_usb_ids;
	int result;

	US_DEBUGP("USB Mass Storage device detected\n");

	us = malloc(sizeof(struct us_data));
	if (!us) {
		printf(USB_STORAGE "Unable to allocate the device\n");
		return -ENOMEM;
	}
	memset(us, 0, sizeof(struct us_data));
	mutex_init(&(us->dev_mutex));
	thread_waiter_init(&us->exit_wait);

	/* Associate the us_data structure with the USB device */
	result = associate_dev(us, intf);
	if (result)
		goto BadDevice;

	/*
	 * Get the unusual_devs entries and the descriptors
	 *
	 * id_index is calculated in the declaration to be the index number
	 * of the match from the usb_device_id table, so we can find the
	 * corresponding entry in the private table.
	 */
	get_device_info(us, id_index);

	/* Get the transport, protocol, and pipe settings */
	result = get_transport(us);
	if (result)
		goto BadDevice;
	result = get_protocol(us);
	if (result)
		goto BadDevice;
	result = get_pipes(us);
	if (result)
		goto BadDevice;

	us->current_urb = usb_alloc_urb(0);
	if (!us->current_urb) {
		US_DEBUGP("URB allocation failed\n");
		result = -ENOMEM;
		goto BadDevice;
	}

	thread_create("usb_stor_scan_work", 4096, usb_stor_scan_work, us);

	return 0;

	/* We come here if there are any problems */
BadDevice:
	US_DEBUGP("storage_probe() failed\n");
	set_bit(US_FLIDX_DISCONNECTING, &us->flags);
	usb_stor_release_resources(us);
	dissociate_dev(us);
	free(us);
	return result;
}

/* Handle a disconnect event from the USB core */
static void storage_disconnect(struct usb_interface *intf)
{
	int i;
	int ret;
	struct usb_storage_device *dev;
	struct us_data *us = intf->private_data;

	US_DEBUGP("storage_disconnect() called\n");

	/* Prevent new USB transfers, stop the current command, and
	 * interrupt a SCSI-scan or device-reset delay */
	set_bit(US_FLIDX_DISCONNECTING, &us->flags);

	/* wait scan_work complete_exit */
	thread_waiter_wait(&us->exit_wait);

	/* Wait for the current command to finish, then remove the host */
	mutex_lock(&us->dev_mutex);
	mutex_unlock(&us->dev_mutex);

	for (i = 0; i <= us->max_lun; i++) {
		dev = &us->storage_device[i];
		if (dev->bind_flag) {
			assert(dev->bind_flag == USB_STORAGE_BIND_FLAG);
			usb_host_mass_storage_unlink(dev);

			/* wait mass storage unbind */
			ret = thread_waiter_wait_timeout(&dev->unbind_wait, USB_STORAGE_UNBIND_WAIT_TIMEOUT);
			if (ret) {
				dev->bind_flag = 0;
				dev->user_data = NULL;
				printf(USB_STORAGE "ERROR !!! unbind timeout, force unbind.\n");
			}
		}
	}

	/* Wait for the current command to finish, then remove the host */
	mutex_lock(&us->dev_mutex);
	mutex_unlock(&us->dev_mutex);

	/* Wait for everything to become idle and release all our resources */
	usb_stor_release_resources(us);
	dissociate_dev(us);

	free(us);
}

void usb_host_mass_storage_unbind(struct usb_storage_device *dev)
{
	assert(dev);
	assert(dev->bind_flag == USB_STORAGE_BIND_FLAG);

	dev->bind_flag = 0;
	thread_waiter_wakeup(&dev->unbind_wait);
}


int usb_host_mass_storage_write(struct usb_storage_device *dev, u8 *buffer, u32 sector, u16 count)
{
	assert(dev && buffer);

	if (count == 0)
		return 0;

	assert(dev->private_data);
	assert(dev->index < USB_STORAGE_MAX_LUNS);
	assert(dev->bind_flag == USB_STORAGE_BIND_FLAG);

	return usb_stor_scsi_write10(dev->private_data, dev->index, dev->block_size, buffer, sector, count);
}

int usb_host_mass_storage_read(struct usb_storage_device *dev, u8 *buffer, u32 sector, u16 count)
{
	assert(dev && buffer);

	if (count == 0)
		return 0;

	assert(dev->private_data);
	assert(dev->index < USB_STORAGE_MAX_LUNS);
	assert(dev->bind_flag == USB_STORAGE_BIND_FLAG);

	/* todo ... if fail try to use read6 */
	return usb_stor_scsi_read10(dev->private_data, dev->index, dev->block_size, buffer, sector, count);
}

static struct usb_driver usb_storage_driver = {
	.name =		"usb-storage",
	.probe =	storage_probe,
	.disconnect =	storage_disconnect,
	.id_table =	storage_usb_ids,
};

void usb_mass_storage_driver_register(void)
{
	usb_register_driver(&usb_storage_driver);
}

void usb_mass_storage_driver_deregister(void)
{
	usb_deregister(&usb_storage_driver);
}
